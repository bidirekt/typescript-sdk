import { Document, Pair, Scalar, YAMLMap, YAMLSeq } from 'yaml'
import type { NamedSchema, Property, SchemaNode } from '../model/contract.ts'
import type {
  Contract,
  ProtocolModule,
  SchemaVocabulary,
} from '../protocols.ts'

const header = ' Generated by @bidirekt/typescript-sdk. Do not edit.'

export function contractToYaml(
  contract: Contract,
  protocols: ReadonlyArray<ProtocolModule>,
): string {
  const root = new YAMLMap()
  if (contract.provides.size > 0) {
    root.add(new Pair('provides', blocksToYaml(contract.provides, protocols)))
  }
  if (contract.consumes.size > 0) {
    root.add(new Pair('consumes', consumedToYaml(contract.consumes, protocols)))
  }
  if (contract.schemas.length > 0) {
    root.add(new Pair('schemas', schemasToYaml(contract.schemas)))
  }
  const document = new Document(root)
  root.commentBefore = header
  return document.toString({
    flowCollectionPadding: false,
    lineWidth: 0,
    nullStr: '~',
  })
}

export function compareBytes(a: string, b: string): number {
  return Buffer.compare(Buffer.from(a), Buffer.from(b))
}

export function sortedByKey<T>(groups: Map<string, T>): Array<[string, T]> {
  return [...groups].sort(([a], [b]) => compareBytes(a, b))
}

function consumedToYaml(
  consumes: Map<string, Map<string, unknown>>,
  protocols: ReadonlyArray<ProtocolModule>,
): YAMLMap {
  const providers = new YAMLMap()
  for (const [name, blocks] of sortedByKey(consumes)) {
    providers.add(new Pair(name, blocksToYaml(blocks, protocols)))
  }
  return providers
}

function blocksToYaml(
  blocks: Map<string, unknown>,
  protocols: ReadonlyArray<ProtocolModule>,
): YAMLMap {
  const byProtocol = new YAMLMap()
  const sorted = [...protocols].sort((a, b) => compareBytes(a.name, b.name))
  for (const protocol of sorted) {
    if (blocks.has(protocol.name)) {
      const block = protocol.toYaml(blocks.get(protocol.name))
      byProtocol.add(new Pair(protocol.name, block))
    }
  }
  return byProtocol
}

function schemasToYaml(schemas: Array<NamedSchema>): YAMLMap {
  const named = new YAMLMap()
  const sorted = [...schemas].sort((a, b) => compareBytes(a.name, b.name))
  for (const schema of sorted) {
    named.add(new Pair(schema.name, nodeToYaml(schema.node, schema.vocabulary)))
  }
  return named
}

function nodeToYaml(
  node: SchemaNode,
  vocabulary: SchemaVocabulary | undefined,
): YAMLMap {
  const fields = new YAMLMap()
  switch (node.type) {
    case 'ref':
      fields.add(new Pair('ref', node.schema))
      break
    case 'object':
      fields.add(new Pair('type', node.type))
      fields.add(new Pair('properties', propertiesToYaml(node.properties)))
      break
    case 'array':
      fields.add(new Pair('type', node.type))
      fields.add(new Pair('items', nodeToYaml(node.items, vocabulary)))
      break
    case 'map':
      fields.add(new Pair('type', node.type))
      fields.add(new Pair('values', nodeToYaml(node.values, vocabulary)))
      break
    case 'enum':
      fields.add(new Pair('type', node.type))
      fields.add(new Pair('members', enumMembersToYaml(node.members)))
      break
    case 'union': {
      fields.add(new Pair('type', node.type))
      if (node.properties !== undefined) {
        fields.add(new Pair('properties', propertiesToYaml(node.properties)))
      }
      const members = new YAMLMap()
      for (const member of node.members) {
        members.add(new Pair(member.key, nodeToYaml(member.node, vocabulary)))
      }
      fields.add(new Pair('members', members))
      break
    }
    default:
      fields.add(new Pair('type', node.type))
  }
  if (node.extra !== undefined) {
    vocabulary?.toYaml(node, fields)
  }
  if (node.optional) {
    fields.add(new Pair('optional', true))
  }
  if (node.nullable) {
    fields.add(new Pair('nullable', true))
  }
  if (node.description !== undefined) {
    fields.add(new Pair('description', node.description))
  }
  return fields
}

function propertiesToYaml(properties: Array<Property>): YAMLMap {
  const map = new YAMLMap()
  for (const property of properties) {
    map.add(
      new Pair(property.name, nodeToYaml(property.node, property.vocabulary)),
    )
  }
  return map
}

function enumMembersToYaml(members: Array<string>): YAMLSeq {
  const sequence = new YAMLSeq()
  sequence.flow = true
  for (const member of members) {
    const scalar = new Scalar(member)
    scalar.type = Scalar.QUOTE_DOUBLE
    sequence.add(scalar)
  }
  return sequence
}
