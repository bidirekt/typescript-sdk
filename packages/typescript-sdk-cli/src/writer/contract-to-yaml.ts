import { Document, Pair, Scalar, YAMLMap, YAMLSeq } from 'yaml'
import type {
  Body,
  ConsumedResource,
  Contract,
  NamedSchema,
  ProvidedResource,
  SchemaNode,
} from '../model/contract.ts'

const header = ' Generated by @bidirekt/typescript-sdk. Do not edit.'

export function contractToYaml(contract: Contract): string {
  const root = new YAMLMap()
  if (contract.provides.length > 0) {
    root.add(new Pair('provides', providedToYaml(contract.provides)))
  }
  if (contract.consumes.length > 0) {
    root.add(new Pair('consumes', consumedToYaml(contract.consumes)))
  }
  if (contract.schemas.length > 0) {
    root.add(new Pair('schemas', schemasToYaml(contract.schemas)))
  }
  const document = new Document(root)
  root.commentBefore = header
  return document.toString({
    flowCollectionPadding: false,
    lineWidth: 0,
    nullStr: '~',
  })
}

function compareBytes(a: string, b: string): number {
  return Buffer.compare(Buffer.from(a), Buffer.from(b))
}

function sortedByKey<T>(
  groups: Map<string, Array<T>>,
): Array<[string, Array<T>]> {
  return [...groups].sort(([a], [b]) => compareBytes(a, b))
}

function providedToYaml(resources: Array<ProvidedResource>): YAMLMap {
  const rest = new YAMLMap()
  rest.add(new Pair('rest', resourcesToYaml(resources)))
  return rest
}

function consumedToYaml(resources: Array<ConsumedResource>): YAMLMap {
  const providers = new YAMLMap()
  const byProvider = Map.groupBy(resources, (resource) => resource.provider)
  for (const [name, own] of sortedByKey(byProvider)) {
    providers.add(new Pair(name, providedToYaml(own)))
  }
  return providers
}

function resourcesToYaml(resources: Array<ProvidedResource>): YAMLMap {
  const endpoints = new YAMLMap()
  const byPath = Map.groupBy(resources, (resource) => resource.path)
  for (const [path, own] of sortedByKey(byPath)) {
    const methods = new YAMLMap()
    const atPath = own
      .map((resource) => ({
        method: resource.method.toLowerCase(),
        resource,
      }))
      .sort((a, b) => compareBytes(a.method, b.method))
    for (const { method, resource } of atPath) {
      methods.add(new Pair(method, resourceToYaml(resource)))
    }
    endpoints.add(new Pair(path, methods))
  }
  return endpoints
}

function resourceToYaml(resource: ProvidedResource): YAMLMap {
  const interaction = new YAMLMap()
  if (resource.request) {
    interaction.add(new Pair('request', bodyToYaml(resource.request)))
  }
  const responses = new YAMLMap()
  const byStatus = [...resource.responses].sort((a, b) => a.status - b.status)
  for (const response of byStatus) {
    responses.add(new Pair(response.status, bodyToYaml(response)))
  }
  interaction.add(new Pair('responses', responses))
  return interaction
}

function bodyToYaml(body: Body): Scalar {
  return new Scalar(body.schema)
}

function schemasToYaml(schemas: Array<NamedSchema>): YAMLMap {
  const named = new YAMLMap()
  const sorted = [...schemas].sort((a, b) => compareBytes(a.name, b.name))
  for (const schema of sorted) {
    named.add(new Pair(schema.name, nodeToYaml(schema.node)))
  }
  return named
}

function nodeToYaml(node: SchemaNode): YAMLMap {
  const fields = new YAMLMap()
  switch (node.type) {
    case 'ref':
      fields.add(new Pair('ref', node.schema))
      break
    case 'object': {
      fields.add(new Pair('type', node.type))
      const properties = new YAMLMap()
      for (const property of node.properties) {
        properties.add(new Pair(property.name, nodeToYaml(property.node)))
      }
      fields.add(new Pair('properties', properties))
      break
    }
    case 'array':
      fields.add(new Pair('type', node.type))
      fields.add(new Pair('items', nodeToYaml(node.items)))
      break
    case 'map':
      fields.add(new Pair('type', node.type))
      fields.add(new Pair('values', nodeToYaml(node.values)))
      break
    case 'enum':
      fields.add(new Pair('type', node.type))
      fields.add(new Pair('members', enumMembersToYaml(node.members)))
      break
    case 'union': {
      fields.add(new Pair('type', node.type))
      const members = new YAMLMap()
      for (const member of node.members) {
        members.add(new Pair(member.key, nodeToYaml(member.node)))
      }
      fields.add(new Pair('members', members))
      break
    }
    default:
      fields.add(new Pair('type', node.type))
  }
  if (node.optional) {
    fields.add(new Pair('optional', true))
  }
  if (node.nullable) {
    fields.add(new Pair('nullable', true))
  }
  if (node.description !== undefined) {
    fields.add(new Pair('description', node.description))
  }
  return fields
}

function enumMembersToYaml(members: Array<string>): YAMLSeq {
  const sequence = new YAMLSeq()
  sequence.flow = true
  for (const member of members) {
    const scalar = new Scalar(member)
    scalar.type = Scalar.QUOTE_DOUBLE
    sequence.add(scalar)
  }
  return sequence
}
