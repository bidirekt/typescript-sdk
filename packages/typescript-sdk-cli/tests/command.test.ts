import assert from 'node:assert/strict'
import {
  existsSync,
  mkdtempSync,
  mkdirSync,
  readFileSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { after, describe, it } from 'node:test'
import ts from 'typescript'
import { Pair, YAMLMap } from 'yaml'
import { runCommand } from '../src/command.ts'
import { defaultProtocols } from '../src/protocols.ts'
import type { ProtocolModule } from '../src/protocols.ts'

const root = mkdtempSync(join(tmpdir(), 'command-'))

after(() => rmSync(root, { recursive: true, force: true }))

const usage =
  'Usage: typescript-sdk generate [--check] [--project <tsconfig>] [--out <file>]\n'

const header = '# Generated by @bidirekt/typescript-sdk. Do not edit.\n'

const annotatedPet = [
  "import { BidirektField, BidirektSchema } from '@bidirekt/typescript-sdk'",
  '',
  '@BidirektSchema()',
  'export class Pet {',
  "  @BidirektField({ type: 'string' })",
  '  name',
  '}',
  '',
].join('\n')

const sdkExportBorrowedAsFieldDecorator = 'BidirektRestConsumer'

const tickets: ProtocolModule<number> = {
  name: 'tickets',
  exports: {
    [sdkExportBorrowedAsFieldDecorator]: {
      isTarget: ts.isPropertyDeclaration,
      description: 'a property',
    },
  },
  tagKeywords: [],
  read: () => ({ blocks: [], derived: [], errors: [] }),
  merge: (sideBlocks) => ({ block: sideBlocks.length, errors: [] }),
  references: () => [],
  isEmpty: (block) => block === 0,
  toYaml: () => new YAMLMap(),
  vocabulary: {
    fieldDecorator: sdkExportBorrowedAsFieldDecorator,
    fieldOptions: ['scalar', 'arguments'],
    toNode: (options, node) => ({ ...node, extra: options }),
    toYaml: (node, map) => {
      const { scalar, arguments: fieldArguments } = node.extra ?? {}
      if (typeof scalar === 'string') {
        map.set('type', 'scalar')
        map.add(new Pair('name', scalar))
      }
      if (typeof fieldArguments === 'string') {
        map.add(new Pair('arguments', fieldArguments))
      }
    },
    references: (node) => {
      const fieldArguments = node.extra?.arguments
      if (typeof fieldArguments !== 'string') {
        return []
      }
      return [fieldArguments]
    },
  },
}

function writeProject(name: string, files: Record<string, string>): string {
  const directory = join(root, name)
  mkdirSync(directory, { recursive: true })
  for (const [path, content] of Object.entries(files)) {
    mkdirSync(dirname(join(directory, path)), { recursive: true })
    writeFileSync(join(directory, path), content)
  }
  return directory
}

describe('runCommand', () => {
  it('prints the usage without the generate command', () => {
    const result = runCommand([], root)

    assert.deepEqual(result, { exitCode: 1, stderr: usage })
    assert.equal(existsSync(join(root, 'contracts')), false)
  })

  it('prints the usage on an unknown option', () => {
    const result = runCommand(['generate', '--watch'], root)

    assert.deepEqual(result, { exitCode: 1, stderr: usage })
    assert.equal(existsSync(join(root, 'contracts')), false)
  })

  it('writes contracts/generated.yaml next to the tsconfig.json of the cwd', () => {
    const directory = writeProject('tsconfig', {
      'tsconfig.json': '{}',
      'pet.ts': annotatedPet,
    })

    const result = runCommand(['generate'], directory)

    const output = join(directory, 'contracts', 'generated.yaml')
    assert.deepEqual(result, { exitCode: 0, stderr: '' })
    assert.ok(readFileSync(output, 'utf8').startsWith(header))
  })

  it('prefers tsconfig.json over jsconfig.json', () => {
    const directory = writeProject('both-configs', {
      'tsconfig.json': JSON.stringify({ include: ['typed'] }),
      'jsconfig.json': JSON.stringify({ include: ['plain'] }),
      'plain/pet.js': annotatedPet,
    })

    const result = runCommand(['generate'], directory)

    assert.equal(result.exitCode, 1)
    assert.equal(
      result.stderr,
      'no @bidirekt/typescript-sdk annotation found in "tsconfig.json": nothing to generate\n',
    )
  })

  it('reads the jsconfig.json of the cwd when there is no tsconfig.json', () => {
    const directory = writeProject('jsconfig', {
      'jsconfig.json': '{}',
      'pet.js': annotatedPet,
    })

    const result = runCommand(['generate'], directory)

    assert.equal(result.exitCode, 0)
    assert.ok(existsSync(join(directory, 'contracts', 'generated.yaml')))
  })

  it('writes next to the --project config and to --out relative to the cwd', () => {
    const directory = writeProject('project-and-out', {
      'apps/api/tsconfig.json': '{}',
      'apps/api/pet.ts': annotatedPet,
    })

    const toProject = runCommand(
      ['generate', '--project', 'apps/api/tsconfig.json'],
      directory,
    )
    const toOut = runCommand(
      ['generate', '--project', 'apps/api/tsconfig.json', '--out', 'out.yaml'],
      directory,
    )

    assert.deepEqual(toProject, { exitCode: 0, stderr: '' })
    assert.ok(
      existsSync(join(directory, 'apps', 'api', 'contracts', 'generated.yaml')),
    )
    assert.deepEqual(toOut, { exitCode: 0, stderr: '' })
    assert.ok(existsSync(join(directory, 'out.yaml')))
  })

  it('fails on a --project that does not exist', () => {
    const directory = writeProject('missing-project', {})

    const result = runCommand(
      ['generate', '--project', 'apps/tsconfig.json'],
      directory,
    )

    assert.deepEqual(result, {
      exitCode: 1,
      stderr: 'project "apps/tsconfig.json" not found\n',
    })
    assert.equal(existsSync(join(directory, 'contracts')), false)
  })

  it('prints a config error as file:line message and writes nothing', () => {
    const directory = writeProject('broken-config', {
      'tsconfig.json': '{\n  "compilerOptions": [\n',
      'pet.ts': annotatedPet,
    })

    const result = runCommand(['generate'], directory)

    assert.equal(result.exitCode, 1)
    assert.match(result.stderr, /^tsconfig\.json:\d+ \S/)
    assert.equal(existsSync(join(directory, 'contracts')), false)
  })

  it('fails without writing when there is no annotation', () => {
    const directory = writeProject('no-annotation', {
      'pet.ts': 'export class Pet {}\n',
    })

    const result = runCommand(['generate'], directory)

    assert.equal(result.exitCode, 1)
    assert.equal(
      result.stderr,
      'no @bidirekt/typescript-sdk annotation found in ".": nothing to generate\n',
    )
    assert.equal(existsSync(join(directory, 'contracts')), false)
  })

  it('checks without writing', () => {
    const directory = writeProject('check', { 'pet.ts': annotatedPet })
    const output = join(directory, 'contracts', 'generated.yaml')

    const missing = runCommand(['generate', '--check'], directory)
    const writtenByMissing = existsSync(output)
    runCommand(['generate'], directory)
    const upToDate = runCommand(['generate', '--check'], directory)
    writeFileSync(output, `${header}schemas: {}\n`)
    const outOfDate = runCommand(['generate', '--check'], directory)

    assert.deepEqual(missing, {
      exitCode: 1,
      stderr:
        '"contracts/generated.yaml" does not exist: run generate without --check\n',
    })
    assert.equal(writtenByMissing, false)
    assert.deepEqual(upToDate, { exitCode: 0, stderr: '' })
    assert.deepEqual(outOfDate, {
      exitCode: 1,
      stderr:
        '"contracts/generated.yaml" is out of date: run generate without --check\n',
    })
    assert.equal(readFileSync(output, 'utf8'), `${header}schemas: {}\n`)
  })

  it('checks a contract written with CRLF line endings as up to date', () => {
    const directory = writeProject('check-crlf', { 'pet.ts': annotatedPet })
    const output = join(directory, 'contracts', 'generated.yaml')
    runCommand(['generate'], directory)
    writeFileSync(output, readFileSync(output, 'utf8').replaceAll('\n', '\r\n'))

    const result = runCommand(['generate', '--check'], directory)

    assert.deepEqual(result, { exitCode: 0, stderr: '' })
  })

  it('reports a two-line tag description the same with CRLF line endings', () => {
    const taggedPet = [
      '/** @bidirekt schema */',
      'export class Pet {',
      '  /**',
      '   * @bidirekt field type=string description="The name',
      '   * the owner calls the pet"',
      '   */',
      '  name',
      '}',
      '',
    ].join('\n')
    const lf = writeProject('tags-lf', { 'pet.js': taggedPet })
    const crlf = writeProject('tags-crlf', {
      'pet.js': taggedPet.replaceAll('\n', '\r\n'),
    })

    const lfResult = runCommand(['generate'], lf)
    const crlfResult = runCommand(['generate'], crlf)

    const rejected = {
      exitCode: 1,
      stderr:
        'pet.js:4 description "The name\\nthe owner calls the pet" must be ASCII letters and digits, with single spaces between words: remove or replace the other characters\n',
    }
    assert.deepEqual(lfResult, rejected)
    assert.deepEqual(crlfResult, rejected)
    assert.equal(existsSync(join(lf, 'contracts')), false)
    assert.equal(existsSync(join(crlf, 'contracts')), false)
  })

  it('fails without a stack trace when --out is a directory', () => {
    const directory = writeProject('out-directory', {
      'pet.ts': annotatedPet,
      'out/keep.txt': '',
    })

    const written = runCommand(['generate', '--out', 'out'], directory)
    const checked = runCommand(
      ['generate', '--check', '--out', 'out'],
      directory,
    )

    assert.equal(written.exitCode, 1)
    assert.match(written.stderr, /^cannot write "out": EISDIR: [^\n]+\n$/)
    assert.equal(checked.exitCode, 1)
    assert.match(checked.stderr, /^cannot read "out": EISDIR: [^\n]+\n$/)
  })

  it('fails on an "extends" it cannot read and writes nothing', () => {
    const missingFile = writeProject('extends-missing-file', {
      'tsconfig.json': '{\n  "extends": "./tsconfig.bse.json"\n}\n',
      'tsconfig.base.json': '{}',
      'pet.ts': annotatedPet,
    })
    const missingPackage = writeProject('extends-missing-package', {
      'tsconfig.json':
        '{\n  "include": ["*.ts"],\n  "extends": "@tsconfig/node22/tsconfig.json"\n}\n',
      'pet.ts': annotatedPet,
    })

    const fromMissingFile = runCommand(['generate'], missingFile)
    const fromMissingPackage = runCommand(['generate'], missingPackage)

    const message =
      'cannot read the config that "extends" names: fix the path or install the package that provides it'
    assert.deepEqual(fromMissingFile, {
      exitCode: 1,
      stderr: `tsconfig.json:2 ${message}\n`,
    })
    assert.deepEqual(fromMissingPackage, {
      exitCode: 1,
      stderr: `tsconfig.json:3 ${message}\n`,
    })
    assert.equal(existsSync(join(missingFile, 'contracts')), false)
    assert.equal(existsSync(join(missingPackage, 'contracts')), false)
  })

  it('fails on a tsconfig with only project references and names them', () => {
    const directory = writeProject('solution', {
      'tsconfig.json': JSON.stringify(
        {
          files: [],
          references: [
            { path: './tsconfig.app.json' },
            { path: './tsconfig.node.json' },
          ],
        },
        null,
        2,
      ),
      'tsconfig.app.json': JSON.stringify({
        compilerOptions: { composite: true },
        include: ['src'],
      }),
      'tsconfig.node.json': JSON.stringify({
        compilerOptions: { composite: true },
        include: ['vite.config.ts'],
      }),
      'src/pet.ts': annotatedPet,
    })

    const result = runCommand(['generate'], directory)
    const fromReference = runCommand(
      ['generate', '--project', 'tsconfig.app.json'],
      directory,
    )

    assert.deepEqual(result, {
      exitCode: 1,
      stderr:
        'tsconfig.json:3 the project has no files, only project references: run generate with --project and one of "./tsconfig.app.json", "./tsconfig.node.json"\n',
    })
    assert.deepEqual(fromReference, { exitCode: 0, stderr: '' })
  })

  it('reads a workspace package linked into node_modules as project code', () => {
    const workspace = writeProject('workspace', {
      'packages/dto/package.json': JSON.stringify({
        name: '@acme/dto',
        type: 'module',
        exports: { '.': './src/index.ts' },
      }),
      'packages/dto/src/index.ts': [
        "import { BidirektField, BidirektSchema } from '@bidirekt/typescript-sdk'",
        '',
        'export class Entity {',
        '  @BidirektField()',
        '  id!: string',
        '}',
        '',
        '@BidirektSchema()',
        'export class Owner {',
        '  @BidirektField()',
        '  name!: string',
        '}',
        '',
      ].join('\n'),
      'apps/api/package.json': JSON.stringify({ type: 'module' }),
      'apps/api/tsconfig.json': JSON.stringify({
        compilerOptions: {
          strict: true,
          module: 'nodenext',
          allowImportingTsExtensions: true,
        },
        include: ['src'],
      }),
      'apps/api/src/pet.ts': [
        "import { BidirektField, BidirektSchema } from '@bidirekt/typescript-sdk'",
        "import { Entity, Owner } from '@acme/dto'",
        '',
        '@BidirektSchema()',
        'export class Pet extends Entity {',
        '  @BidirektField()',
        '  owner!: Owner',
        '}',
        '',
      ].join('\n'),
    })
    const api = join(workspace, 'apps', 'api')
    mkdirSync(join(api, 'node_modules', '@acme'), { recursive: true })
    symlinkSync(
      join(workspace, 'packages', 'dto'),
      join(api, 'node_modules', '@acme', 'dto'),
      'junction',
    )

    const result = runCommand(['generate'], api)

    assert.deepEqual(result, { exitCode: 0, stderr: '' })
    assert.equal(
      readFileSync(join(api, 'contracts', 'generated.yaml'), 'utf8'),
      [
        header.trimEnd(),
        'schemas:',
        '  Owner:',
        '    type: object',
        '    properties:',
        '      name:',
        '        type: string',
        '  Pet:',
        '    type: object',
        '    properties:',
        '      id:',
        '        type: string',
        '      owner:',
        '        ref: Owner',
        '',
      ].join('\n'),
    )
  })

  it('stops on a REST decorator when no protocol is registered', () => {
    const directory = writeProject('rest-decorator-without-protocols', {
      'pets.ts': [
        "import { BidirektRestProvider } from '@bidirekt/typescript-sdk'",
        '',
        'export class PetsController {',
        "  @BidirektRestProvider({ method: 'GET', path: '/pets', responses: { 204: null } })",
        '  list() {}',
        '}',
        '',
      ].join('\n'),
    })

    const result = runCommand(['generate'], directory, [])

    assert.deepEqual(result, {
      exitCode: 1,
      stderr:
        'pets.ts:4 BidirektRestProvider: no registered protocol reads it\n',
    })
    assert.equal(existsSync(join(directory, 'contracts')), false)
  })

  it('stops on a REST tag when no protocol is registered', () => {
    const directory = writeProject('rest-tag-without-protocols', {
      'pets.ts': [
        '/**',
        ' * @bidirekt rest provides GET /pets',
        ' * @bidirekt response 204',
        ' */',
        'export function listPets() {}',
        '',
      ].join('\n'),
    })

    const result = runCommand(['generate'], directory, [])

    assert.deepEqual(result, {
      exitCode: 1,
      stderr: [
        'pets.ts:2 unknown tag "@bidirekt rest": use schema or field',
        'pets.ts:3 unknown tag "@bidirekt response": use schema or field',
        '',
      ].join('\n'),
    })
    assert.equal(existsSync(join(directory, 'contracts')), false)
  })

  it('writes the same schemas with and without the REST protocol', () => {
    const files = {
      'pet.ts': annotatedPet,
      'owner.ts': [
        '/** @bidirekt schema */',
        'export interface Owner {',
        '  /** @bidirekt field type=integer */',
        '  id: number',
        '}',
        '',
      ].join('\n'),
    }
    const withRest = writeProject('schemas-with-rest', files)
    const withoutRest = writeProject('schemas-without-rest', files)

    const withRestResult = runCommand(['generate'], withRest)
    const withoutRestResult = runCommand(['generate'], withoutRest, [])

    const schemas = [
      header.trimEnd(),
      'schemas:',
      '  Owner:',
      '    type: object',
      '    properties:',
      '      id:',
      '        type: integer',
      '  Pet:',
      '    type: object',
      '    properties:',
      '      name:',
      '        type: string',
      '',
    ].join('\n')
    assert.deepEqual(withRestResult, { exitCode: 0, stderr: '' })
    assert.deepEqual(withoutRestResult, { exitCode: 0, stderr: '' })
    assert.equal(
      readFileSync(join(withRest, 'contracts', 'generated.yaml'), 'utf8'),
      schemas,
    )
    assert.equal(
      readFileSync(join(withoutRest, 'contracts', 'generated.yaml'), 'utf8'),
      schemas,
    )
  })

  it('reads the field decorator and the field tag of a registered vocabulary', () => {
    const directory = writeProject('vocabulary-fields', {
      'ticket.ts': [
        'import {',
        '  BidirektField,',
        `  ${sdkExportBorrowedAsFieldDecorator} as TicketField,`,
        '  BidirektSchema,',
        "} from '@bidirekt/typescript-sdk'",
        '',
        '@BidirektSchema()',
        'export class ReplyArgs {',
        '  @BidirektField()',
        '  first!: string',
        '}',
        '',
        '@BidirektSchema()',
        'export class Ticket {',
        "  @TicketField({ scalar: 'DateTime', optional: true })",
        '  openedAt!: string',
        '',
        '  @TicketField({ arguments: ReplyArgs })',
        '  replies!: string',
        '}',
        '',
      ].join('\n'),
      'note.ts': [
        '/** @bidirekt schema */',
        'export interface Note {',
        '  /** @bidirekt tickets field scalar=DateTime arguments=ReplyArgs */',
        '  writtenAt: string',
        '}',
        '',
      ].join('\n'),
    })

    const result = runCommand(['generate'], directory, [tickets])

    assert.deepEqual(result, { exitCode: 0, stderr: '' })
    assert.equal(
      readFileSync(join(directory, 'contracts', 'generated.yaml'), 'utf8'),
      [
        header.trimEnd(),
        'schemas:',
        '  Note:',
        '    type: object',
        '    properties:',
        '      writtenAt:',
        '        type: scalar',
        '        name: DateTime',
        '        arguments: ReplyArgs',
        '  ReplyArgs:',
        '    type: object',
        '    properties:',
        '      first:',
        '        type: string',
        '  Ticket:',
        '    type: object',
        '    properties:',
        '      openedAt:',
        '        type: scalar',
        '        name: DateTime',
        '        optional: true',
        '      replies:',
        '        type: string',
        '        arguments: ReplyArgs',
        '',
      ].join('\n'),
    )
  })

  it('rejects a schema a vocabulary references when no schema has its name', () => {
    const directory = writeProject('vocabulary-missing-schema', {
      'note.ts': [
        '/** @bidirekt schema */',
        'export interface Note {',
        '  /** @bidirekt tickets field arguments=NoteArgs */',
        '  replies: string',
        '}',
        '',
      ].join('\n'),
    })

    const result = runCommand(['generate'], directory, [tickets])

    assert.deepEqual(result, {
      exitCode: 1,
      stderr:
        'note.ts:4 schema "NoteArgs" is not declared: reference a schema by its name in the contract\n',
    })
  })

  it('accepts on a vocabulary field only the field options and the options of the vocabulary', () => {
    const directory = writeProject('vocabulary-unknown-options', {
      'ticket.ts': [
        'import {',
        `  ${sdkExportBorrowedAsFieldDecorator} as TicketField,`,
        '  BidirektSchema,',
        "} from '@bidirekt/typescript-sdk'",
        '',
        '@BidirektSchema()',
        'export class Ticket {',
        "  @TicketField({ scalr: 'DateTime' })",
        '  openedAt!: string',
        '}',
        '',
      ].join('\n'),
      'note.ts': [
        '/** @bidirekt schema */',
        'export interface Note {',
        '  /** @bidirekt tickets field scalr=DateTime */',
        '  writtenAt: string',
        '}',
        '',
      ].join('\n'),
    })

    const result = runCommand(['generate'], directory, [tickets])

    assert.deepEqual(result, {
      exitCode: 1,
      stderr: [
        'note.ts:3 cannot read "scalr=DateTime" in "@bidirekt tickets field": write "<key>=<value>" with key type, name, optional, nullable, description, union, scalar or arguments',
        `ticket.ts:8 unknown option "scalr" in @${sdkExportBorrowedAsFieldDecorator} options: write name, description, optional, nullable, type, union, scalar or arguments`,
        '',
      ].join('\n'),
    })
  })

  it('reads the field tag of a vocabulary in a schema of a handler comment', () => {
    const directory = writeProject('vocabulary-handler-comment', {
      'health.ts': [
        '/**',
        ' * @bidirekt rest provides GET /health',
        ' * @bidirekt response 200 Health',
        ' * @bidirekt schema Health',
        ' * @bidirekt tickets field checkedAt type=string scalar=DateTime',
        ' */',
        'export function health() {}',
        '',
      ].join('\n'),
    })
    const ticketTags: ProtocolModule<number> = { ...tickets, exports: {} }

    const result = runCommand(['generate'], directory, [
      ...defaultProtocols,
      ticketTags,
    ])

    assert.deepEqual(result, { exitCode: 0, stderr: '' })
    assert.equal(
      readFileSync(join(directory, 'contracts', 'generated.yaml'), 'utf8'),
      [
        header.trimEnd(),
        'provides:',
        '  rest:',
        '    /health:',
        '      get:',
        '        responses:',
        '          200: Health',
        'schemas:',
        '  Health:',
        '    type: object',
        '    properties:',
        '      checkedAt:',
        '        type: scalar',
        '        name: DateTime',
        '',
      ].join('\n'),
    )
  })
})
