import assert from 'node:assert/strict'
import { execFileSync, spawnSync } from 'node:child_process'
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { after, before, describe, it } from 'node:test'

const repository = join(import.meta.dirname, '..', '..', '..')
const workspace = mkdtempSync(join(tmpdir(), 'package-'))

after(() => rmSync(workspace, { recursive: true, force: true }))

type Packed = {
  name: string
  version: string
  filename: string
  files: Array<{ path: string }>
}

const runtimeName = '@bidirekt/typescript-sdk'
const cliName = '@bidirekt/typescript-sdk-cli'

const petSource = [
  "import { BidirektField, BidirektSchema } from '@bidirekt/typescript-sdk'",
  '',
  '@BidirektSchema()',
  'export class Pet {',
  "  @BidirektField({ type: 'integer' })",
  '  id!: number',
  '}',
  '',
].join('\n')

const petContract = [
  '# Generated by @bidirekt/typescript-sdk. Do not edit.',
  'schemas:',
  '  Pet:',
  '    type: object',
  '    properties:',
  '      id:',
  '        type: integer',
  '',
].join('\n')

const npmCli = process.env.npm_execpath ?? ''
const tscBin = fileURLToPath(import.meta.resolve('typescript/bin/tsc'))

function npm(args: Array<string>, cwd: string): string {
  assert.ok(npmCli, 'run the tests with npm, which sets npm_execpath')
  return execFileSync(process.execPath, [npmCli, ...args], {
    cwd,
    encoding: 'utf8',
  })
}

function node(args: Array<string>, cwd: string): string {
  return execFileSync(process.execPath, args, { cwd, encoding: 'utf8' })
}

function writeProject(name: string, manifest: object): string {
  const project = join(workspace, name)
  mkdirSync(project)
  writeFileSync(
    join(project, 'package.json'),
    JSON.stringify({ private: true, type: 'module', ...manifest }),
  )
  writeFileSync(join(project, 'tsconfig.json'), '{}')
  writeFileSync(join(project, 'pet.ts'), petSource)
  return project
}

function install(project: string, args: Array<string>): void {
  npm(
    ['install', '--no-audit', '--no-fund', '--prefer-offline', ...args],
    project,
  )
}

function isInstalled(project: string, name: string): boolean {
  return existsSync(join(project, 'node_modules', name))
}

function assertGeneratesPetContract(project: string): void {
  const result = spawnSync(
    process.execPath,
    [npmCli, 'exec', '--no', '--', cliName, 'generate'],
    { cwd: project, encoding: 'utf8' },
  )

  assert.equal(result.stderr, '')
  assert.equal(result.status, 0)
  assert.equal(
    readFileSync(join(project, 'contracts', 'generated.yaml'), 'utf8'),
    petContract,
  )
}

describe('npm pack', () => {
  const packed = new Map<string, Packed>()

  function tarball(name: string): string {
    const found = packed.get(name)
    assert.ok(found, `${name} is packed`)
    return `file:${join(workspace, found.filename)}`
  }

  before(
    () => {
      npm(['run', 'build', '--workspace', cliName], repository)
      const packedList = JSON.parse(
        npm(
          ['pack', '--workspaces', '--json', '--pack-destination', workspace],
          repository,
        ),
      ) as Array<Packed>
      for (const each of packedList) {
        packed.set(each.name, each)
      }
    },
    { timeout: 300_000 },
  )

  it('packs both packages at one version, each with its dist, README and LICENSE', () => {
    const shippedPaths = {
      [runtimeName]: [
        'dist/index.js',
        'dist/index.cjs',
        'dist/index.d.ts',
        'dist/index.d.cts',
      ],
      [cliName]: ['dist/cli.js'],
    }
    for (const [name, paths] of Object.entries(shippedPaths)) {
      const shipped = packed.get(name)?.files.map((file) => file.path) ?? []
      for (const path of [...paths, 'package.json', 'README.md', 'LICENSE']) {
        assert.ok(shipped.includes(path), `${name} ships ${path}`)
      }
    }
    const runtimeVersion = packed.get(runtimeName)?.version
    assert.equal(packed.get(cliName)?.version, runtimeVersion)
    const cliManifest = JSON.parse(
      readFileSync(
        join(repository, 'packages', 'typescript-sdk-cli', 'package.json'),
        'utf8',
      ),
    ) as { dependencies: Record<string, string> }
    assert.equal(cliManifest.dependencies[runtimeName], runtimeVersion)
  })

  it(
    'installs only the runtime in a production install of a project with decorators',
    { timeout: 300_000 },
    () => {
      const project = writeProject('production', {
        dependencies: { [runtimeName]: tarball(runtimeName) },
        devDependencies: { [cliName]: tarball(cliName) },
      })

      install(project, ['--omit=dev'])

      assert.ok(isInstalled(project, runtimeName), 'the runtime is installed')
      for (const name of [cliName, 'typescript', 'yaml']) {
        assert.equal(
          isInstalled(project, name),
          false,
          `${name} is not installed`,
        )
      }
    },
  )

  it(
    'generates the contract of a project with the runtime installed',
    { timeout: 300_000 },
    () => {
      const project = writeProject('with-runtime', {
        dependencies: { [runtimeName]: tarball(runtimeName) },
        devDependencies: { [cliName]: tarball(cliName) },
      })

      install(project, [])

      assertGeneratesPetContract(project)
    },
  )

  it(
    'generates the contract of a project without the runtime installed',
    { timeout: 300_000 },
    () => {
      const project = writeProject('without-runtime', {
        devDependencies: { [cliName]: tarball(cliName) },
        // The runtime is not on the registry yet: the CLI's dependency comes from its tarball.
        overrides: { [runtimeName]: tarball(runtimeName) },
      })

      install(project, ['--install-strategy=nested'])

      assert.equal(
        isInstalled(project, runtimeName),
        false,
        'the runtime is not installed in the project',
      )
      assertGeneratesPetContract(project)
    },
  )

  for (const moduleType of ['commonjs', 'module']) {
    it(
      `type-checks the decorators in a ${moduleType} project with module node16`,
      { timeout: 300_000 },
      () => {
        const project = writeProject(`types-${moduleType}`, {
          type: moduleType,
          dependencies: { [runtimeName]: tarball(runtimeName) },
        })
        writeFileSync(
          join(project, 'tsconfig.json'),
          JSON.stringify({
            compilerOptions: {
              strict: true,
              experimentalDecorators: true,
              module: 'node16',
              target: 'es2022',
              types: [],
              noEmit: true,
            },
            files: ['pet.ts'],
          }),
        )
        install(project, [])

        const result = spawnSync(process.execPath, [tscBin, '-p', project], {
          encoding: 'utf8',
        })

        assert.equal(result.stdout, '')
        assert.equal(result.status, 0)
      },
    )
  }

  it(
    'loads the runtime with require and with import',
    { timeout: 300_000 },
    () => {
      const project = writeProject('module-formats', {
        type: 'commonjs',
        dependencies: { [runtimeName]: tarball(runtimeName) },
      })
      install(project, [])

      const required = node(
        [
          '-e',
          `const sdk = require('${runtimeName}'); console.log(JSON.stringify([Object.keys(sdk).sort(), require.resolve('${runtimeName}')]))`,
        ],
        project,
      )
      const imported = node(
        [
          '--input-type=module',
          '-e',
          `import * as sdk from '${runtimeName}'; console.log(JSON.stringify([Object.keys(sdk).sort(), import.meta.resolve('${runtimeName}')]))`,
        ],
        project,
      )

      const decorators = [
        'BidirektConsumer',
        'BidirektField',
        'BidirektProvider',
        'BidirektSchema',
      ]
      const [requiredNames, requiredEntry] = JSON.parse(required) as [
        Array<string>,
        string,
      ]
      const [importedNames, importedEntry] = JSON.parse(imported) as [
        Array<string>,
        string,
      ]
      assert.deepEqual(requiredNames, decorators)
      assert.ok(requiredEntry.endsWith('index.cjs'), requiredEntry)
      assert.deepEqual(importedNames, decorators)
      assert.ok(importedEntry.endsWith('index.js'), importedEntry)
    },
  )
})
