describe('contractToYaml', () => {
  it('writes every node type and flag in the fixed order', () => {
    assert.equal(contractToYaml(fullContract(), []), fullYaml)
  })

  it('writes the same text for the same model', () => {
    assert.equal(
      contractToYaml(fullContract(), []),
      contractToYaml(fullContract(), []),
    )
  })

  it('writes the same text when schemas arrive in another order', () => {
    const contract = fullContract()
    const reversed: Contract = {
      ...contract,
      schemas: [...contract.schemas].reverse(),
    }
    assert.equal(contractToYaml(reversed, []), fullYaml)
  })

  it('writes the properties of a union before its members', () => {
    const contract: Contract = {
      provides: new Map(),
      consumes: new Map(),
      schemas: [
        {
          name: 'Node',
          location: at,
          node: {
            type: 'union',
            properties: [
              { name: 'id', location: at, node: { type: 'string' } },
              {
                name: 'createdAt',
                location: at,
                node: { type: 'string', extra: { scalar: 'DateTime' } },
                vocabulary: scalars.vocabulary,
              },
            ],
            members: [
              { key: 'User', node: { type: 'ref', schema: 'UserName' } },
              { key: 'Pet', node: { type: 'ref', schema: 'PetSpecies' } },
            ],
          },
        },
      ],
    }
    assert.equal(
      contractToYaml(contract, [scalars]),
      `# Generated by @bidirekt/typescript-sdk. Do not edit.
schemas:
  Node:
    type: union
    properties:
      id:
        type: string
      createdAt:
        type: scalar
        name: DateTime
    members:
      User:
        ref: UserName
      Pet:
        ref: PetSpecies
`,
    )
  })

  it('writes each block under its protocol, by protocol and by provider name', () => {
    const contract: Contract = {
      provides: new Map([
        ['calls', 1],
        ['audits', 2],
      ]),
      consumes: new Map([
        ['payments_api', new Map([['calls', 3]])],
        [
          'auth_api',
          new Map([
            ['calls', 4],
            ['audits', 5],
          ]),
        ],
      ]),
      schemas: [],
    }
    assert.equal(
      contractToYaml(contract, [calls, audits]),
      `# Generated by @bidirekt/typescript-sdk. Do not edit.
provides:
  audits:
    calls: 2
  calls:
    calls: 1
consumes:
  auth_api:
    audits:
      calls: 5
    calls:
      calls: 4
  payments_api:
    calls:
      calls: 3
`,
    )
  })

  it('omits empty sections', () => {
    const contract: Contract = {
      provides: new Map(),
      consumes: new Map([['payments_api', new Map([['calls', 1]])]]),
      schemas: [],
    }
    assert.equal(
      contractToYaml(contract, [calls]),
      `# Generated by @bidirekt/typescript-sdk. Do not edit.
consumes:
  payments_api:
    calls:
      calls: 1
`,
    )
  })

  it('writes the extra of a node with the vocabularies, before its flags', () => {
    const contract: Contract = {
      provides: new Map(),
      consumes: new Map(),
      schemas: [
        {
          name: 'Ticket',
          location: at,
          node: {
            type: 'object',
            properties: [
              {
                name: 'openedAt',
                location: at,
                node: {
                  type: 'string',
                  optional: true,
                  extra: { scalar: 'DateTime' },
                },
                vocabulary: scalars.vocabulary,
              },
              { name: 'closedAt', location: at, node: { type: 'string' } },
            ],
          },
        },
      ],
    }
    assert.equal(
      contractToYaml(contract, [scalars]),
      `# Generated by @bidirekt/typescript-sdk. Do not edit.
schemas:
  Ticket:
    type: object
    properties:
      openedAt:
        type: scalar
        name: DateTime
        optional: true
      closedAt:
        type: string
`,
    )
  })

  it('writes the extra of a node only with the vocabulary that owns it', () => {
    const contract: Contract = {
      provides: new Map(),
      consumes: new Map(),
      schemas: [
        {
          name: 'Ticket',
          location: at,
          node: {
            type: 'object',
            properties: [
              {
                name: 'openedAt',
                location: at,
                node: { type: 'string', extra: { name: 'DateTime' } },
                vocabulary: scalarNames.vocabulary,
              },
              {
                name: 'contact',
                location: at,
                node: { type: 'string', extra: { name: 'Email' } },
                vocabulary: formatNames.vocabulary,
              },
              {
                name: 'closedAt',
                location: at,
                node: {
                  type: 'array',
                  items: { type: 'string', extra: { name: 'DateTime' } },
                },
                vocabulary: scalarNames.vocabulary,
              },
            ],
          },
        },
        {
          name: 'Email',
          location: at,
          node: { type: 'string', extra: { name: 'Email' } },
          vocabulary: formatNames.vocabulary,
        },
      ],
    }
    assert.equal(
      contractToYaml(contract, [scalarNames, formatNames]),
      `# Generated by @bidirekt/typescript-sdk. Do not edit.
schemas:
  Email:
    type: format
    name: Email
  Ticket:
    type: object
    properties:
      openedAt:
        type: scalar
        name: DateTime
      contact:
        type: format
        name: Email
      closedAt:
        type: array
        items:
          type: scalar
          name: DateTime
`,
    )
  })

  it('double-quotes enum members YAML would read as another type', () => {
    const contract: Contract = {
      provides: new Map(),
      consumes: new Map(),
      schemas: [
        {
          name: 'Answer',
          location: at,
          node: {
            type: 'enum',
            members: ['true', '1', 'null', 'yes', '~', 'say "hi"'],
          },
        },
      ],
    }
    assert.equal(
      contractToYaml(contract, []),
      `# Generated by @bidirekt/typescript-sdk. Do not edit.
schemas:
  Answer:
    type: enum
    members: ["true", "1", "null", "yes", "~", "say \\"hi\\""]
`,
    )
  })
})
