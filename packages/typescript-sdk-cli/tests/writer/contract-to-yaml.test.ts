describe('contractToYaml', () => {
  it('writes every node type and flag in the fixed order', () => {
    assert.equal(contractToYaml(fullContract()), fullYaml)
  })

  it('writes the same text for the same model', () => {
    assert.equal(contractToYaml(fullContract()), contractToYaml(fullContract()))
  })

  it('writes the same text when resources and schemas arrive in another order', () => {
    const contract = fullContract()
    const reversed: Contract = {
      provides: contract.provides
        .map((resource) => ({
          ...resource,
          responses: [...resource.responses].reverse(),
        }))
        .reverse(),
      consumes: [...contract.consumes].reverse(),
      schemas: [...contract.schemas].reverse(),
    }
    assert.equal(contractToYaml(reversed), fullYaml)
  })

  it('omits empty sections and the request key when none was declared', () => {
    const contract: Contract = {
      provides: [],
      consumes: [
        {
          provider: 'payments_api',
          method: 'GET',
          path: '/charges/*',
          responses: [{ status: 200, schema: null, location: at }],
          location: at,
        },
      ],
      schemas: [],
    }
    assert.equal(
      contractToYaml(contract),
      `# Generated by @bidirekt/typescript-sdk. Do not edit.
consumes:
  payments_api:
    rest:
      /charges/*:
        get:
          responses:
            200: ~
`,
    )
  })

  it('double-quotes enum members YAML would read as another type', () => {
    const contract: Contract = {
      provides: [],
      consumes: [],
      schemas: [
        {
          name: 'Answer',
          location: at,
          node: {
            type: 'enum',
            members: ['true', '1', 'null', 'yes', '~', 'say "hi"'],
          },
        },
      ],
    }
    assert.equal(
      contractToYaml(contract),
      `# Generated by @bidirekt/typescript-sdk. Do not edit.
schemas:
  Answer:
    type: enum
    members: ["true", "1", "null", "yes", "~", "say \\"hi\\""]
`,
    )
  })
})
