import assert from 'node:assert/strict'
import { describe, it } from 'node:test'
import { Pair, YAMLMap } from 'yaml'
import type { SourceLocation } from '../../src/model/contract.ts'
import type { Contract, ProtocolModule } from '../../src/protocols.ts'
import { contractToYaml } from '../../src/writer/contract-to-yaml.ts'

const at: SourceLocation = { file: 'src/pets.ts', line: 1 }

function countingProtocol(name: string): ProtocolModule<number> {
  return {
    name,
    exports: {},
    tagKeywords: [],
    read: () => ({ blocks: [], derived: [], errors: [] }),
    merge: (sideBlocks) => ({ block: sideBlocks.length, errors: [] }),
    references: () => [],
    isEmpty: (block) => block === 0,
    toYaml: (block) => {
      const map = new YAMLMap()
      map.add(new Pair('calls', block))
      return map
    },
  }
}

const calls = countingProtocol('calls')

const scalars: ProtocolModule<number> = {
  ...countingProtocol('scalars'),
  vocabulary: {
    label: 'Scalars',
    fieldDecorator: 'ScalarField',
    fieldOptions: ['scalar'],
    toNode: (options, node) => ({ ...node, extra: options }),
    toYaml: (node, map) => {
      const scalar = node.extra?.scalar
      if (typeof scalar === 'string') {
        map.set('type', 'scalar')
        map.add(new Pair('name', scalar))
      }
    },
    references: () => [],
  },
}

const audits = countingProtocol('audits')

function namingProtocol(name: string, type: string): ProtocolModule<number> {
  return {
    ...countingProtocol(name),
    vocabulary: {
      label: name,
      fieldDecorator: `${name}Field`,
      fieldOptions: ['name'],
      toNode: (options, node) => ({ ...node, extra: options }),
      toYaml: (node, map) => {
        const named = node.extra?.name
        if (typeof named === 'string') {
          map.set('type', type)
          map.add(new Pair('name', named))
        }
      },
      references: () => [],
    },
  }
}

const scalarNames = namingProtocol('scalarNames', 'scalar')

const formatNames = namingProtocol('formatNames', 'format')

