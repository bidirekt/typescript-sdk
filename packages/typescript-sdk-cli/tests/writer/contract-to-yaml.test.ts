describe('contractToYaml', () => {
  it('writes every node type and flag in the fixed order', () => {
    assert.equal(contractToYaml(fullContract(), []), fullYaml)
  })

  it('writes the same text for the same model', () => {
    assert.equal(
      contractToYaml(fullContract(), []),
      contractToYaml(fullContract(), []),
    )
  })

  it('writes the same text when schemas arrive in another order', () => {
    const contract = fullContract()
    const reversed: Contract = {
      ...contract,
      schemas: [...contract.schemas].reverse(),
    }
    assert.equal(contractToYaml(reversed, []), fullYaml)
  })

  it('writes each block under its protocol, by protocol and by provider name', () => {
    const contract: Contract = {
      provides: new Map([
        ['calls', 1],
        ['audits', 2],
      ]),
      consumes: new Map([
        ['payments_api', new Map([['calls', 3]])],
        [
          'auth_api',
          new Map([
            ['calls', 4],
            ['audits', 5],
          ]),
        ],
      ]),
      schemas: [],
    }
    assert.equal(
      contractToYaml(contract, [calls, audits]),
      `# Generated by @bidirekt/typescript-sdk. Do not edit.
provides:
  audits:
    calls: 2
  calls:
    calls: 1
consumes:
  auth_api:
    audits:
      calls: 5
    calls:
      calls: 4
  payments_api:
    calls:
      calls: 3
`,
    )
  })

  it('omits empty sections', () => {
    const contract: Contract = {
      provides: new Map(),
      consumes: new Map([['payments_api', new Map([['calls', 1]])]]),
      schemas: [],
    }
    assert.equal(
      contractToYaml(contract, [calls]),
      `# Generated by @bidirekt/typescript-sdk. Do not edit.
consumes:
  payments_api:
    calls:
      calls: 1
`,
    )
  })

  it('double-quotes enum members YAML would read as another type', () => {
    const contract: Contract = {
      provides: new Map(),
      consumes: new Map(),
      schemas: [
        {
          name: 'Answer',
          location: at,
          node: {
            type: 'enum',
            members: ['true', '1', 'null', 'yes', '~', 'say "hi"'],
          },
        },
      ],
    }
    assert.equal(
      contractToYaml(contract, []),
      `# Generated by @bidirekt/typescript-sdk. Do not edit.
schemas:
  Answer:
    type: enum
    members: ["true", "1", "null", "yes", "~", "say \\"hi\\""]
`,
    )
  })
})
